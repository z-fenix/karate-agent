package io.karatelabs.parser;

public enum NodeType {
   TOKEN,
   ERROR,
   ROOT,
   PROGRAM,
   STATEMENT,
   IF_STMT,
   VAR_STMT,
   VAR_NAMES,
   VAR_DECL,
   RETURN_STMT,
   TRY_STMT,
   THROW_STMT,
   FOR_STMT,
   WHILE_STMT,
   DO_WHILE_STMT,
   SWITCH_STMT,
   CASE_BLOCK,
   DEFAULT_BLOCK,
   BREAK_STMT,
   CONTINUE_STMT,
   LABELLED_STMT,
   DELETE_EXPR,
   BLOCK,
   EOS,
   EXPR,
   EXPR_LIST,
   FN_EXPR,
   FN_ARROW_EXPR,
   FN_DECL_ARGS,
   FN_DECL_ARG,
   NEW_EXPR,
   TYPEOF_EXPR,
   INSTANCEOF_EXPR,
   IN_EXPR,
   FN_CALL_EXPR,
   FN_CALL_ARGS,
   FN_CALL_ARG,
   FN_TAGGED_TEMPLATE_EXPR,
   ASSIGN_EXPR,
   LOGIC_EXPR,
   LOGIC_AND_EXPR,
   LOGIC_NULLISH_EXPR,
   LOGIC_TERN_EXPR,
   LOGIC_BIT_EXPR,
   MATH_ADD_EXPR,
   MATH_MUL_EXPR,
   MATH_EXP_EXPR,
   MATH_POST_EXPR,
   MATH_PRE_EXPR,
   PATH_EXPR,
   REF_EXPR,
   REF_DOT_EXPR,
   REF_BRACKET_EXPR,
   UNARY_EXPR,
   AWAIT_EXPR,
   YIELD_EXPR,
   LIT_OBJECT,
   OBJECT_ELEM,
   LIT_ARRAY,
   ARRAY_ELEM,
   LIT_EXPR,
   PAREN_EXPR,
   LIT_TEMPLATE,
   PLACEHOLDER,
   LIT_REGEX,
   CLASS_EXPR,
   CLASS_METHOD,
   CLASS_FIELD,
   CLASS_STATIC_BLOCK,
   SUPER_EXPR,
   PRIVATE_NAME_EXPR,
   G_FEATURE,
   G_TAGS,
   G_NAME_DESC,
   G_BACKGROUND,
   G_SCENARIO,
   G_SCENARIO_OUTLINE,
   G_EXAMPLES,
   G_STEP,
   G_STEP_LINE,
   G_DOC_STRING,
   G_TABLE,
   G_TABLE_ROW;

   public final int expectedChildren = expectedChildrenFor(this);

   private static int expectedChildrenFor(NodeType type) {
      return switch (type) {
         case TOKEN -> 0;
         default -> 4;
         case ROOT, CASE_BLOCK, DEFAULT_BLOCK, BLOCK, LIT_TEMPLATE, CLASS_EXPR, G_FEATURE, G_BACKGROUND, G_SCENARIO, G_SCENARIO_OUTLINE, G_EXAMPLES, G_STEP, G_STEP_LINE, G_DOC_STRING, G_TABLE -> 16;
         case PROGRAM -> 8;
         case STATEMENT, BREAK_STMT, CONTINUE_STMT, EXPR_LIST, FN_DECL_ARG, TYPEOF_EXPR, FN_CALL_ARG, FN_TAGGED_TEMPLATE_EXPR, MATH_POST_EXPR, MATH_PRE_EXPR, UNARY_EXPR, AWAIT_EXPR, ARRAY_ELEM, PLACEHOLDER, LIT_REGEX -> 2;
         case VAR_DECL, LABELLED_STMT, INSTANCEOF_EXPR, IN_EXPR, REF_DOT_EXPR, YIELD_EXPR -> 3;
         case FOR_STMT -> 9;
         case EOS, EXPR, REF_EXPR, LIT_EXPR, PRIVATE_NAME_EXPR -> 1;
         case FN_DECL_ARGS -> 6;
         case FN_CALL_ARGS, LOGIC_TERN_EXPR -> 5;
         case LIT_OBJECT, LIT_ARRAY -> 12;
         case G_TABLE_ROW -> 12;
      };
   }
}
